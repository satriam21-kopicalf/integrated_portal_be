-- 040: Waste (2026-10-31, user request): the outlets, HUB and PICs enter every wasted item of their branch; Cost
-- Control monitors and reviews it (pages waste, cc.waste-monitor, cc.waste-review). One row per item: the branch, the
-- business day, the scope (waste, usage = Usage Management, premix = a premix / WIP recipe of the premix calculator,
-- kc_recipe, in grams), the quantity in the item's unit, the waste category, a camera photo (evidence, stamped with
-- the time and the branch) and a note / reason. Items and categories come from docs/Daily SO & Waste.xlsx
-- (integrated_portal); premix items are read live from kc_recipe (app/waste.py).

CREATE TABLE IF NOT EXISTS integration_portal.waste_item (
    scope      text     NOT NULL CHECK (scope IN ('waste', 'usage')),
    code       text     NOT NULL,
    name       text     NOT NULL,
    unit       text     NOT NULL,
    sort       integer  NOT NULL DEFAULT 0,
    is_active  boolean  NOT NULL DEFAULT true,
    PRIMARY KEY (scope, code)
);

CREATE TABLE IF NOT EXISTS integration_portal.waste_category (
    id         serial   PRIMARY KEY,
    name       text     NOT NULL UNIQUE,
    sort       integer  NOT NULL DEFAULT 0,
    is_active  boolean  NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS integration_portal.waste_entry (
    id             uuid           PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id        uuid           NOT NULL,
    username       text           NOT NULL,
    full_name      text,
    role           text           NOT NULL,
    branch_code    text           NOT NULL,
    branch_name    text           NOT NULL,
    business_date  date           NOT NULL,
    scope          text           NOT NULL CHECK (scope IN ('waste', 'usage', 'premix')),
    item_code      text           NOT NULL,
    item_name      text           NOT NULL,
    unit           text           NOT NULL,
    qty            numeric(14, 3) NOT NULL CHECK (qty > 0),
    category       text           NOT NULL,
    note           text,
    photo          bytea          NOT NULL,
    photo_type     text           NOT NULL,
    photo_taken_at timestamptz,
    latitude       numeric(9, 6),
    longitude      numeric(9, 6),
    status         text           NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted', 'approved', 'rejected')),
    review_note    text,
    reviewed_by    text,
    reviewed_at    timestamptz,
    device         text,
    ip             text,
    created_at     timestamptz    NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS waste_entry_day_idx ON integration_portal.waste_entry (business_date DESC, branch_code);
CREATE INDEX IF NOT EXISTS waste_entry_status_idx ON integration_portal.waste_entry (status, business_date DESC);
CREATE INDEX IF NOT EXISTS waste_entry_user_idx ON integration_portal.waste_entry (user_id, created_at DESC);

