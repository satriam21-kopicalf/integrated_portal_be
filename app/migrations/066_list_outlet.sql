INSERT INTO integration_portal.branch_group_member (branch_code, group_id)
SELECT l.branch_code, g.id FROM list_outlet l JOIN integration_portal.branch_group g ON g.code = l.grp
ON CONFLICT (branch_code) DO UPDATE SET group_id = EXCLUDED.group_id, added_at = now();

UPDATE kc_master.facility f SET latitude = l.lat, longitude = l.lon, updated_at = now()
  FROM list_outlet l
  JOIN integration_esb.master_branches b ON b.branch_code = l.branch_code
  JOIN kc_master.facility_esb_map m ON m.company_code = b.company_code AND m.esb_id = b.branch_id::text
 WHERE f.id = m.facility_id;

UPDATE kc_master.facility f SET checkin_radius_m = 50, updated_at = now()
  FROM integration_esb.master_branches b
  JOIN kc_master.facility_esb_map m ON m.company_code = b.company_code AND m.esb_id = b.branch_id::text
 WHERE f.id = m.facility_id AND b.branch_name ILIKE 'Kopi Calf%' AND f.checkin_radius_m IS DISTINCT FROM 50;

